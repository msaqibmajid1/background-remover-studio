export const getPresetCategories = (): string[] => {
  const categories = new Set(textStylePresets.map(p => p.category));
  return Array.from(categories);
};

export const getPresetsByCategory = (category: string): TextStylePreset[] => {
  return textStylePresets.filter(p => p.category === category);
};

export const searchPresets = (query: string): TextStylePreset[] => {
  const lowercaseQuery = query.toLowerCase();
  return textStylePresets.filter(p => 
    p.name.toLowerCase().includes(lowercaseQuery) ||
    p.category.toLowerCase().includes(lowercaseQuery)
  );
};
