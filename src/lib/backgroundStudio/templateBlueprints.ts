function templateNameKey(name: string) {
  return name.replace(/\.[^.]+$/, "").toLowerCase().replace(/[^a-z0-9]+/g, "");
}

export function bundledTemplateForName(name: string) {
  const key = templateNameKey(name),
    alias = legacyTemplateAliases[key];
  return CINEMA_TEMPLATES.find(
    (source) =>
      source.id === alias ||
      templateNameKey(source.name) === key ||
      templateNameKey(source.file) === key,
  );
}
