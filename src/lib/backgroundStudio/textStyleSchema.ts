import { z } from "zod";
const n = z.number().finite();
const paint = z.string().max(300);
const mode = z.enum(["first", "last", "random", "numbers", "cycle", "line"]);
const lineFields = {
  firstN: n.int().min(0).max(10000).optional(),
  lastN: n.int().min(0).max(10000).optional(),
  randomPercent: n.min(0).max(100).optional(),
  lineN: n.int().min(1).max(10000).optional(),
  lineCount: n.int().min(1).max(10000).optional(),
  lineFrom: z.enum(["first", "last", "specific"]).optional(),
  lineColorMode: z.enum(["solid", "cycle"]).optional(),
  slotIds: z.array(n.int()).max(100).optional(),
};
const word = z.object({
  wordIndex: n.int().min(0).max(10000),
  color: paint,
  colorType: z.enum(["solid", "gradient"]).optional(),
  gradientStartColor: paint.optional(),
  gradientEndColor: paint.optional(),
  gradientDirection: z.enum(["horizontal", "vertical", "diagonal-down", "diagonal-up", "radial"]).optional(),
  backgroundColor: paint.optional(),
  bold: z.boolean().optional(),
  italic: z.boolean().optional(),
});
export const studioTextStyleSchema = z
  .object({
    fontWeight: z.string().max(20),
    fontStyle: z.string().max(20),
    textDecoration: z.string().max(30),
    textTransform: z.enum(["none", "uppercase", "lowercase", "capitalize"]),
    textAlign: z.enum(["left", "center", "right", "justify"]),
    verticalAlign: z.enum(["top", "middle", "bottom"]),
    lineHeight: n.min(0.1).max(10),
    letterSpacing: n.min(-100).max(300),
    wordSpacing: n.min(-100).max(300),
    autoFitText: z.boolean(),
    dimensionsLocked: z.boolean(),
    colorType: z.enum(["solid", "gradient"]),
    gradientColor: z.string().max(2000),
    gradientStartColor: paint,
    gradientEndColor: paint,
    gradientDirection: z.enum([
      "horizontal",
      "vertical",
      "diagonal-down",
      "diagonal-up",
      "radial",
    ]),
    strokeColor: paint,
    strokeWidth: n.min(0).max(100),
    shadow: z.boolean(),
    shadowColor: paint,
    shadowBlur: n.min(0).max(200),
    shadowOffsetX: n.min(-500).max(500),
    shadowOffsetY: n.min(-500).max(500),
    backgroundColor: paint,
    backgroundOpacity: n.min(0).max(1),
    backgroundPadding: n.min(0).max(300),
    backgroundRadius: n.min(0).max(500),
    textBoxBorder: z.boolean(),
    textBoxBorderColor: paint,
    textBoxBorderWidth: n.min(0).max(100),
    textBoxBorderRadius: n.min(0).max(500),
    textBoxBorderStyle: z.enum([
      "solid",
      "dashed",
      "dotted",
      "double",
      "groove",
      "ridge",
    ]),
    textBoxBorderDashPattern: z.array(n.min(0).max(500)).max(30),
    textBoxBorderTop: z.boolean(),
    textBoxBorderRight: z.boolean(),
    textBoxBorderBottom: z.boolean(),
    textBoxBorderLeft: z.boolean(),
    textBoxBorderShadow: z.boolean(),
    textBoxBorderShadowColor: paint,
    textBoxBorderShadowBlur: n.min(0).max(200),
    textBoxBorderShadowOffsetX: n.min(-500).max(500),
    textBoxBorderShadowOffsetY: n.min(-500).max(500),
    textBoxFillType: z.enum(["solid", "gradient"]),
    textBoxGradientFill: z.string().max(2000),
    textBoxGradientStartColor: paint,
    textBoxGradientEndColor: paint,
    textBoxGradientDirection: z.enum([
      "horizontal",
      "vertical",
      "diagonal-down",
      "diagonal-up",
      "radial",
    ]),
    curveAngle: n.min(-360).max(360),
    textPath: z.string().max(50),
    customPath: z.string().max(100000),
    pathOffset: n.min(0).max(100),
    wordStyles: z.array(word).max(10000),
    wordStylesEnabled: z.boolean(),
    wordStyleBgPadding: n.min(0).max(100),
    wordStyleBgRadius: n.min(0).max(100),
    wordStyleRules: z.object({
      slots: z
        .array(
          z.object({
            id: n.int(),
            color: paint,
            colorType: z.enum(["solid", "gradient"]).optional(),
            gradientStartColor: paint.optional(),
            gradientEndColor: paint.optional(),
            gradientDirection: z.enum(["horizontal", "vertical", "diagonal-down", "diagonal-up", "radial"]).optional(),
            backgroundColor: paint.optional(),
            bold: z.boolean(),
            italic: z.boolean(),
          }),
        )
        .max(100),
      mode: z.enum([
        "manual",
        "first",
        "last",
        "random",
        "numbers",
        "cycle",
        "preset",
        "composite",
        "line",
      ]),
      ...lineFields,
      presetName: z.string().max(200).optional(),
      steps: z
        .array(z.object({ mode, slotId: n.int(), ...lineFields }))
        .max(100)
        .optional(),
    }),
    outlineGlow: z.boolean(),
    outlineGlowColor: paint,
    outlineGlowBlur: n.min(0).max(100),
    outlineGlowSpread: n.min(0).max(100),
    parallelogramSlant: n.min(-80).max(80),
    skewX: n.min(-80).max(80),
    skewY: n.min(-80).max(80),
    flipHorizontal: z.boolean(),
    flipVertical: z.boolean(),
  })
  .partial();
